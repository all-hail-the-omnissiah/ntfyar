/// Splits ntfy tags into (emoji prefix, remaining plain tags), like the official apps do.
pub fn split_tags(tags: &[String]) -> (String, Vec<String>) {
    let mut emojis = String::new();
    let mut rest = Vec::new();
    for t in tags {
        match lookup(t.trim()) {
            Some(e) => emojis.push_str(e),
            None => rest.push(t.clone()),
        }
    }
    (emojis, rest)
}
